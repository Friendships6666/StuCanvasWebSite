// 🚀 1. 默认数据模板（已彻底砍掉冗余的 "predicates" 数组）
const DEFAULT_TEMPLATE = {
    "enumTag": "GeometryType",
    "enumPredicate": "PredicateID",
    "types": {
        "Line": ["is_continuous", "is_convex", "is_trivial"],
        "Ellipse": ["is_continuous", "is_convex", "is_trivial"],
        "Spline": ["is_continuous"],
        "Sphere": ["is_3D", "is_surface", "is_continuous", "is_convex", "is_trivial"],
        "Paraboloid": ["is_3D", "is_surface", "is_continuous", "is_convex"],
        "Hyperboloid": ["is_3D", "is_surface", "is_continuous"],
        "Torus": ["is_3D", "is_surface", "is_continuous"],
        "Cube": ["is_3D", "is_convex", "is_trivial"],
        "Cylinder": ["is_3D", "is_convex"],
        "Cone": ["is_3D", "is_convex"]
    }
};

/**
 * 辅助函数：将驼峰或帕斯卡命名转换为下划线命名（如 GeometryType -> geometry_type）
 */
const toSnakeCase = (str) => {
    return str.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
};

/**
 * 核心 C++23 代码生成函数 (已适配 Allman 宽松风格与多系统并存冲突隔离)
 */
function generateCppPredicateSystem(config) {
    const { enumTag, enumPredicate, types } = config;

    // 🚀 2. 动态扫描提取算法：从 types 的属性中自动推导并去重所有唯一的 predicates
    const predicateSet = new Set();
    for (const type in types) {
        if (Array.isArray(types[type])) {
            types[type].forEach(p => {
                if (typeof p === 'string' && p.trim() !== '') {
                    predicateSet.add(p.trim());
                }
            });
        }
    }
    // 确定性排序，防止因 JSON 声明顺序不同导致生成的 C++ 枚举数值发生意外抖动
    const predicates = Array.from(predicateSet).sort();

    // 格式化函数：将 "is_3D" -> "Is3D", "is_surface" -> "IsSurface"
    const formatEnumLabel = (str) => {
        let formatted = str.replace(/_([a-z0-9])/gi, (match, letter) => letter.toUpperCase());
        return formatted.charAt(0).toUpperCase() + formatted.slice(1);
    };

    const typeNames = Object.keys(types);
    const formattedPredicates = predicates.map(p => formatEnumLabel(p));
    const snakeTag = toSnakeCase(enumTag);

    let code = ``;

    code += `// =====================================================================\n`;
    code += `// 🚀 GENERATED CODE - DO NOT MODIFY DIRECTLY\n`;
    code += `// Generated by custom C++23 Predicate System Generator\n`;
    code += `// =====================================================================\n\n`;
    code += `#pragma once\n`;
    code += `#include <cstdint>\n`;
    code += `#include <array>\n`;
    code += `#include <bitset>\n`;
    code += `#include <type_traits>\n`;
    code += `#include <utility>\n\n`;

    // 开启外层命名空间
    code += `namespace StuCanvas\n`;
    code += `{\n`;

    // 生成具体类等差枚举类型
    code += `    // === 1. 严格等差递增的具体类 ID ===\n`;
    code += `    enum class ${enumTag} : uint32_t\n`;
    code += `    {\n`;
    typeNames.forEach((name, index) => {
        if (index === 0) {
            code += `        ${name} = 0,\n`;
        } else {
            code += `        ${name},\n`;
        }
    });
    code += `        COUNT\n`;
    code += `    };\n\n`;

    // 生成从数据中动态提取出的谓词等差枚举类型
    code += `    // === 2. 严格等差递增的特征谓词 ID (从组件依赖中自动动态提取) ===\n`;
    code += `    enum class ${enumPredicate} : uint32_t\n`;
    code += `    {\n`;
    formattedPredicates.forEach((name, index) => {
        if (index === 0) {
            code += `        ${name} = 0,\n`;
        } else {
            code += `        ${name},\n`;
        }
    });
    code += `        COUNT\n`;
    code += `    };\n\n`;

    // 生成特型注册声明（将 TypeRegistration 加上前缀以彻底隔离不同的谓词系统）
    code += `    // === 3. 编译期元数据声明与偏特化 ===\n`;
    code += `    template < ${enumTag} Tag >\n`;
    code += `    struct ${enumTag}Registration;\n\n`;

    // 遍历生成各具体类的特写声明
    typeNames.forEach(type => {
        const rawPreds = types[type] || [];
        code += `    template <>\n`;
        code += `    struct ${enumTag}Registration< ${enumTag}::${type} >\n`;
        code += `    {\n`;
        if (rawPreds.length === 0) {
            code += `        static constexpr std::array< ${enumPredicate}, 0 > predicates = {};\n`;
        } else {
            const mapped = rawPreds.map(p => `${enumPredicate}::${formatEnumLabel(p)}`).join(", ");
            code += `        static constexpr std::array predicates = { ${mapped} };\n`;
        }
        code += `    };\n`;
    });
    code += `\n`;

    // 生成 2D 位图索引生成器模板
    code += `    // === 4. 编译期自动生成的只读二进制位图索引矩阵 ===\n`;
    code += `    namespace detail\n`;
    code += `    {\n`;
    code += `        template < ${enumTag} Tag >\n`;
    code += `        constexpr bool ${snakeTag}_has_predicate ( ${enumPredicate} pred )\n`;
    code += `        {\n`;
    code += `            for ( auto p : ${enumTag}Registration< Tag >::predicates )\n`;
    code += `            {               if ( p == pred )\n`;
    code += `                {\n`;
    code += `                    return true;\n`;
    code += `                }\n`;
    code += `            }\n`;
    code += `            return false;\n`;
    code += `        }\n\n`;

    code += `        template < size_t... Is >\n`;
    code += `        constexpr std::bitset< sizeof... ( Is ) > make_${snakeTag}_predicate_row ( ${enumPredicate} pred, std::index_sequence< Is... > )\n`;
    code += `        {\n`;
    code += `            std::bitset< sizeof... ( Is ) > row;\n`;
    code += `            ( ( row[ Is ] = ${snakeTag}_has_predicate< static_cast< ${enumTag} > ( Is ) > ( pred ) ), ... );\n`;
    code += `            return row;\n`;
    code += `        }\n\n`;

    code += `        template < size_t... Is >\n`;
    code += `        constexpr std::array< std::bitset< static_cast< size_t > ( ${enumTag}::COUNT ) >, static_cast< size_t > ( ${enumPredicate}::COUNT ) >\n`;
    code += `        make_${snakeTag}_bitmap_index ( std::index_sequence< Is... > )\n`;
    code += `        {\n`;
    code += `            return {\n`;
    code += `                make_${snakeTag}_predicate_row ( static_cast< ${enumPredicate} > ( Is ), std::make_index_sequence< static_cast< size_t > ( ${enumTag}::COUNT ) >{} )...\n`;
    code += `            };\n`;
    code += `        }\n`;
    code += `    }\n\n`;

    code += `    struct alignas ( 64 ) ${enumTag}BitmapIndex\n`;
    code += `    {\n`;
    code += `        static constexpr auto index_matrix = detail::make_${snakeTag}_bitmap_index (\n`;
    code += `            std::make_index_sequence< static_cast< size_t > ( ${enumPredicate}::COUNT ) >{}\n`;
    code += `        );\n`;
    code += `    };\n\n`;

    // 生成纯运行期判断 API
    code += `    // === 5. 纯运行期判定接口：禁止任何模板，禁止编译期计算 ===\n\n`;

    code += `    // 判定单个谓词是否拥有\n`;
    code += `    [[nodiscard]] inline bool has_${snakeTag}_predicate ( ${enumTag} type, ${enumPredicate} pred ) noexcept\n`;
    code += `    {\n`;
    code += `        const size_t type_idx = static_cast< size_t > ( type );\n`;
    code += `        const size_t pred_idx = static_cast< size_t > ( pred );\n\n`;
    code += `        [[assume ( type_idx < static_cast< size_t > ( ${enumTag}::COUNT ) )]];\n`;
    code += `        [[assume ( pred_idx < static_cast< size_t > ( ${enumPredicate}::COUNT ) )]];\n\n`;
    code += `        return ${enumTag}BitmapIndex::index_matrix[ pred_idx ].test ( type_idx );\n`;
    code += `    }\n\n`;

    code += `    // 联合多维谓词聚类判定\n`;
    code += `    [[nodiscard]] inline bool has_all_${snakeTag}_predicates ( ${enumTag} type, const ${enumPredicate}* preds, size_t pred_count ) noexcept\n`;
    code += `    {\n`;
    code += `        const size_t type_idx = static_cast< size_t > ( type );\n`;
    code += `        [[assume ( type_idx < static_cast< size_t > ( ${enumTag}::COUNT ) )]];\n\n`;
    code += `        for ( size_t i = 0; i < pred_count; ++i )\n`;
    code += `        {\n`;
    code += `            const size_t pred_idx = static_cast< size_t > ( preds[ i ] );\n`;
    code += `            [[assume ( pred_idx < static_cast< size_t > ( ${enumPredicate}::COUNT ) )]];\n\n`;
    code += `            if ( !${enumTag}BitmapIndex::index_matrix[ pred_idx ].test ( type_idx ) )\n`;
    code += `            {\n`;
    code += `                return false;\n`;
    code += `            }\n`;
    code += `        }\n`;
    code += `        return true;\n`;
    code += `    }\n`;

    // 关闭命名空间
    code += `} // namespace StuCanvas\n`;

    return code;
}

// 3. UI 交互控制逻辑
document.addEventListener("DOMContentLoaded", () => {
    const jsonInput = document.getElementById("json-input");
    const cppOutput = document.getElementById("cpp-output");
    const jsonError = document.getElementById("json-error");

    const btnGenerate = document.getElementById("btn-generate");
    const btnReset = document.getElementById("btn-reset");
    const btnCopy = document.getElementById("btn-copy");
    const copyText = document.getElementById("copy-text");

    // 初始化内容
    const init = () => {
        jsonInput.value = JSON.stringify(DEFAULT_TEMPLATE, null, 2);
        triggerGeneration();
    };

    // 执行生成
    const triggerGeneration = () => {
        try {
            const config = JSON.parse(jsonInput.value);
            jsonError.classList.add("hidden");

            // 基础校验（移除了 predicates 数组校验）
            if (!config.enumTag || !config.enumPredicate || !config.types) {
                throw new Error("Missing required config fields (enumTag, enumPredicate, types).");
            }

            const cppCode = generateCppPredicateSystem(config);
            cppOutput.textContent = cppCode;

            // 重新触发 Prism 语法高亮
            Prism.highlightElement(cppOutput);
        } catch (e) {
            jsonError.textContent = `⚠️ 配置异常: ${e.message}`;
            jsonError.classList.remove("hidden");
        }
    };

    // 绑定事件
    btnGenerate.addEventListener("click", triggerGeneration);
    btnReset.addEventListener("click", init);

    // 一键复制代码
    btnCopy.addEventListener("click", () => {
        navigator.clipboard.writeText(cppOutput.textContent).then(() => {
            copyText.textContent = "已复制!";
            btnCopy.classList.remove("border-blue-800", "text-blue-300");
            btnCopy.classList.add("border-green-700", "text-green-400", "bg-green-950/40");

            setTimeout(() => {
                copyText.textContent = "复制代码";
                btnCopy.classList.remove("border-green-700", "text-green-400", "bg-green-950/40");
                btnCopy.classList.add("border-blue-800", "text-blue-300");
            }, 1500);
        });
    });

    // 实时语法检查（防抖）
    let timer;
    jsonInput.addEventListener("input", () => {
        clearTimeout(timer);
        timer = setTimeout(() => {
            try {
                JSON.parse(jsonInput.value);
                jsonError.classList.add("hidden");
            } catch (e) {
                jsonError.textContent = `⚠️ JSON 格式有误: ${e.message}`;
                jsonError.classList.remove("hidden");
            }
        }, 500);
    });

    init();
});